"""Mutant hunt for a whole test suite: the acceptance tests of this project.

The deliverable of this project is a test suite, so acceptance means: the suite
passes against the real expenses and fails against every mutant in mutants/.

By default it hunts with the reference suite (../reference). To hunt with yours,
set EXPENSES_SUITE to the folder that holds your pyproject.toml and tests/,
for example EXPENSES_SUITE=../your-suite. Do not edit this file.
"""

import os
import subprocess
import sys
from pathlib import Path

import pytest

PROJECT = Path(__file__).resolve().parent.parent
REAL_SOURCE = PROJECT / "reference" / "src"
MUTANTS_DIR = Path(__file__).resolve().parent / "mutants"
MUTANTS = sorted(path.name for path in MUTANTS_DIR.iterdir() if path.is_dir())
TESTS_FAILED = 1  # pytest exit code when tests ran and at least one failed


def suite() -> Path:
    chosen = os.environ.get("EXPENSES_SUITE", "../reference")
    return (Path.cwd() / chosen).resolve()


def run_the_suite(source: Path) -> subprocess.CompletedProcess[str]:
    """Runs the suite with `source` as the only place to import expenses from."""
    env = {key: value for key, value in os.environ.items() if key != "EXPENSES_SUITE"}
    env["PYTHONPATH"] = str(source)
    env["PYTHONIOENCODING"] = "utf-8"  # the child pytest may print symbols a Windows code page can't hold
    return subprocess.run(
        # -o pythonpath= empties the suite's own pythonpath, so PYTHONPATH decides what is imported
        [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "-o", "pythonpath="],
        cwd=suite(), env=env, capture_output=True, text=True, encoding="utf-8", errors="replace",
    )


def last_lines(result: subprocess.CompletedProcess[str], count: int = 15) -> str:
    return "\n".join(result.stdout.strip().splitlines()[-count:])


@pytest.fixture(scope="module")
def against_real_code() -> subprocess.CompletedProcess[str]:
    assert (suite() / "pyproject.toml").is_file(), f"No pyproject.toml in {suite()}: check EXPENSES_SUITE"
    return run_the_suite(REAL_SOURCE)


def test_the_suite_passes_against_the_real_code(against_real_code):
    exit_code = against_real_code.returncode
    assert exit_code == 0, (
        f"The suite in {suite()} must pass against the real expenses before it can catch mutants "
        f"(exit code {exit_code}).\n" + last_lines(against_real_code)
    )


@pytest.mark.parametrize("mutant", MUTANTS)
def test_the_suite_catches(mutant, against_real_code):
    if against_real_code.returncode != 0:
        pytest.fail("First make the suite pass against the real expenses (see the test above).")
    result = run_the_suite(MUTANTS_DIR / mutant)
    exit_code = result.returncode
    assert exit_code == TESTS_FAILED, (
        f"Mutant '{mutant}' survived: the suite still passes when expenses has this bug.\n"
        + last_lines(result, 3)
    )
