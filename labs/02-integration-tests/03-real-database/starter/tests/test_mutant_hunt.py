"""Mutant hunt: your tests must pass against the real scores.py and fail against every mutant.

Do not edit this file. It is ordinary pytest code, so read it if you are curious:
it runs tests/test_scores.py in a separate process, once with the real module and
once per mutant in tests/mutants/.
"""

import os
import subprocess
import sys
from pathlib import Path

import pytest

LAB = Path(__file__).resolve().parent.parent
MUTANTS = sorted(path.name for path in (LAB / "tests" / "mutants").iterdir() if path.is_dir())
TESTS_FAILED = 1  # pytest exit code when tests ran and at least one failed


def run_your_tests(mutant: str | None = None) -> subprocess.CompletedProcess[str]:
    env = {key: value for key, value in os.environ.items() if key != "SCORES_MUTANT"}
    env["PYTHONIOENCODING"] = "utf-8"  # pytest prints symbols like ± that a Windows code page can't hold
    if mutant:
        env["SCORES_MUTANT"] = mutant
    return subprocess.run(
        [sys.executable, "-m", "pytest", "tests/test_scores.py", "-q", "-p", "no:cacheprovider"],
        cwd=LAB, env=env, capture_output=True, text=True, encoding="utf-8", errors="replace",
    )


def last_lines(result: subprocess.CompletedProcess[str], count: int = 15) -> str:
    return "\n".join(result.stdout.strip().splitlines()[-count:])


@pytest.fixture(scope="module")
def against_real_code() -> subprocess.CompletedProcess[str]:
    return run_your_tests()


def test_your_tests_pass_against_the_real_code(against_real_code):
    exit_code = against_real_code.returncode
    assert exit_code == 0, (
        "Your tests must pass against the real scores.py before they can catch mutants.\n"
        + last_lines(against_real_code)
    )


@pytest.mark.parametrize("mutant", MUTANTS)
def test_your_tests_catch(mutant, against_real_code):
    if against_real_code.returncode != 0:
        pytest.fail("First make your tests pass against the real scores.py (see the test above).")
    result = run_your_tests(mutant)
    exit_code = result.returncode
    assert exit_code == TESTS_FAILED, (
        f"Mutant '{mutant}' survived: your tests still pass when scores.py has this bug.\n"
        + last_lines(result, 3)
    )
